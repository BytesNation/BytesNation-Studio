#!/usr/bin/env node
/**
 * Renders docs/inventory/url-parameters.md and docs/inventory/params.json.
 *
 * Sources:
 *   - the engine code (via inventory-params.mjs): every parameter it reads;
 *   - rawdoc.md (upstream docs): summary, role and aliases where documented;
 *   - docs/inventory/param-descriptions.json: code-derived descriptions for
 *     parameters upstream does not document.
 *
 * After an upstream merge, rerun it: new parameters without any description are
 * listed under "Needs description", and the git diff of params.json shows what
 * upstream added, removed or renamed.
 *
 * Usage: node bn-shell/scripts/render-param-inventory.mjs (from the repo root)
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "../..");
const inventoryDir = join(repoRoot, "docs/inventory");

const loadParams = () => {
	const output = execFileSync("node", [join(repoRoot, "bn-shell/scripts/inventory-params.mjs"), repoRoot], { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
	return JSON.parse(output);
};

const escapeCell = text => String(text || "").replace(/\|/g, "\\|").replace(/\n/g, " ");

const roleLabel = role => {
	const normalized = String(role || "").toLowerCase();
	if (normalized.indexOf("sender") === 0) {
		return "Sender";
	}
	if (normalized.indexOf("viewer") === 0) {
		return "Viewer";
	}
	if (normalized.indexOf("director") === 0) {
		return "Director";
	}
	if (normalized.indexOf("general") === 0) {
		return "General";
	}
	return "";
};

/**
 * Joins code-extracted params with descriptions.
 * @returns {{rows: object[], missing: string[]}}
 */
const buildRows = () => {
	const params = loadParams();
	const overlay = JSON.parse(readFileSync(join(inventoryDir, "param-descriptions.json"), "utf8"));
	const missing = [];
	const rows = params.map(entry => {
		const overlayEntry = overlay[entry.param];
		const summary = entry.summary || (overlayEntry ? overlayEntry.summary : "");
		if (!summary) {
			missing.push(entry.param);
		}
		return {
			param: entry.param,
			aliases: entry.aliases,
			role: roleLabel(entry.role || (overlayEntry ? overlayEntry.role : "")),
			summary,
			source: entry.isDocumented ? "upstream docs" : overlayEntry ? "code" : "none",
			isUiFacing: overlayEntry ? Boolean(overlayEntry.isUiFacing) : null,
			firstLocation: entry.firstLocation
		};
	});
	rows.sort((left, right) => left.param.localeCompare(right.param));
	return { rows, missing };
};

const renderMarkdown = ({ rows, missing }) => {
	const aliasCount = rows.reduce((total, row) => total + row.aliases.length, 0);
	const documentedCount = rows.filter(row => row.source === "upstream docs").length;
	const lines = [
		"# URL parameters",
		"",
		"Generated by `bn-shell/scripts/render-param-inventory.mjs`. Do not edit by hand; edit `param-descriptions.json` for code-derived descriptions and rerun.",
		"",
		`${rows.length} parameters (${rows.length + aliasCount} names counting aliases). ${documentedCount} are documented upstream in \`rawdoc.md\`; ${rows.length - documentedCount - missing.length} are described from the code; ${missing.length} need a description.`,
		"",
		"Every parameter here must behave exactly as upstream after the redesign. The redesign changes no parameter parsing: all of it lives in `main.js`, `lib.js` and `webrtc.js`, which BytesNation Studio does not modify. `&classicui` (alias `&bnclassic`) is the only parameter BytesNation adds; it is read by `bn/boot.js`, not the engine.",
		"",
		"Role: Sender (publishing side), Viewer (view and scene side), Director, or General. Source: where the summary comes from.",
		"",
		"| Parameter | Aliases | Role | What it does | Source | Read at |",
		"|---|---|---|---|---|---|"
	];
	rows.forEach(row => {
		const aliasText = row.aliases.map(alias => `\`&${alias}\``).join(", ");
		lines.push(`| \`&${row.param}\` | ${aliasText} | ${row.role} | ${escapeCell(row.summary)} | ${row.source} | \`${row.firstLocation}\` |`);
	});
	if (missing.length > 0) {
		lines.push("", "## Needs description", "", missing.map(name => `- \`&${name}\``).join("\n"));
	}
	return `${lines.join("\n")}\n`;
};

const main = () => {
	const inventory = buildRows();
	writeFileSync(join(inventoryDir, "url-parameters.md"), renderMarkdown(inventory));
	writeFileSync(join(inventoryDir, "params.json"), `${JSON.stringify(inventory.rows, null, "\t")}\n`);
	process.stdout.write(`url-parameters.md: ${inventory.rows.length} parameters, ${inventory.missing.length} need a description\n`);
};

main();
