#!/usr/bin/env node
/**
 * Renders docs/PARITY-CHECKLIST.md and docs/parity/url-parameters.md from the
 * parity suite's JSON results (bn-shell/test-results/parity-results.json).
 * Every checkbox traces to a test run; manual items stay unchecked until a
 * person records the result in docs/parity/manual-results.json.
 *
 * Usage: node bn-shell/scripts/render-parity-checklist.mjs (after `npm run test:parity`)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "../..");
const resultsPath = join(repoRoot, "bn-shell/test-results/parity-results.json");
const manualPath = join(repoRoot, "docs/parity/manual-results.json");
const projects = ["chromium", "firefox", "webkit", "mobile-chrome", "mobile-safari"];
const projectLabels = { chromium: "Chrome", firefox: "Firefox", webkit: "Safari (WebKit)", "mobile-chrome": "Android Chrome", "mobile-safari": "iOS Safari" };

/** Flattens Playwright JSON into {file, title, project, status, annotations}. */
const loadResults = () => {
	const report = JSON.parse(readFileSync(resultsPath, "utf8"));
	const rows = [];
	const walk = (suite, file) => {
		const suiteFile = suite.file || file;
		(suite.specs || []).forEach(spec => {
			spec.tests.forEach(testEntry => {
				const lastResult = testEntry.results[testEntry.results.length - 1] || { status: "skipped" };
				const isSkipped = testEntry.status === "skipped" || lastResult.status === "skipped";
				rows.push({
					file: suiteFile,
					title: spec.title,
					project: testEntry.projectName,
					status: isSkipped ? "skipped" : testEntry.status === "expected" || testEntry.status === "flaky" ? "passed" : "failed",
					isFlaky: testEntry.status === "flaky",
					annotations: (testEntry.annotations || []).concat(lastResult.annotations || [])
				});
			});
		});
		(suite.suites || []).forEach(child => walk(child, suiteFile));
	};
	report.suites.forEach(suite => walk(suite, suite.file));
	return { rows, startTime: report.stats ? report.stats.startTime : "" };
};

const cell = status => ({ passed: "pass", failed: "**FAIL**", skipped: "n/a" })[status] || "not run";

/** One checklist line per test title, with a status per project. */
const renderGroup = (rows, fileName, heading, note) => {
	const groupRows = rows.filter(row => row.file && row.file.endsWith(fileName));
	const titles = [...new Set(groupRows.map(row => row.title))];
	const lines = [`## ${heading}`, ""];
	if (note) {
		lines.push(note, "");
	}
	lines.push(`| | Check | ${projects.map(project => projectLabels[project]).join(" | ")} |`, `|---|---|${projects.map(() => "---").join("|")}|`);
	titles.forEach(title => {
		const statuses = projects.map(project => {
			const match = groupRows.find(row => row.title === title && row.project === project);
			return match ? match.status : "not run";
		});
		const ran = statuses.filter(status => status !== "skipped" && status !== "not run");
		const isChecked = ran.length > 0 && ran.every(status => status === "passed");
		lines.push(`| ${isChecked ? "[x]" : "[ ]"} | ${title.replace(/\|/g, "\\|")} | ${statuses.map(cell).join(" | ")} |`);
	});
	const notes = [...new Set(groupRows.flatMap(row => row.annotations.filter(annotation => annotation.type !== "skip").map(annotation => `${projectLabels[row.project]}: ${annotation.description}`)))];
	if (notes.length > 0) {
		lines.push("", "Notes from the runs:", "", ...notes.map(noteText => `- ${noteText}`));
	}
	return { text: lines.join("\n"), titles, groupRows };
};

const renderParams = rows => {
	const paramRows = rows.filter(row => row.file && row.file.endsWith("params.spec.ts"));
	const titles = [...new Set(paramRows.map(row => row.title))].sort();
	const counts = Object.fromEntries(projects.map(project => {
		const projectRows = paramRows.filter(row => row.project === project && row.status !== "skipped");
		return [project, { ran: projectRows.length, passed: projectRows.filter(row => row.status === "passed").length }];
	}));
	const table = [
		"# URL parameter parity results",
		"",
		"Generated by `bn-shell/scripts/render-parity-checklist.mjs`. Each parameter loads in upstream and in BytesNation Studio side by side, with signaling blocked; the engine's visible elements and state must match. Chrome runs every parameter; the other engines run the UI-facing parameters plus every sixth one.",
		"",
		`| | Parameter | ${projects.map(project => projectLabels[project]).join(" | ")} |`,
		`|---|---|${projects.map(() => "---").join("|")}|`
	];
	titles.forEach(title => {
		const statuses = projects.map(project => {
			const match = paramRows.find(row => row.title === title && row.project === project);
			return match ? match.status : "not run";
		});
		const ran = statuses.filter(status => status !== "skipped" && status !== "not run");
		table.push(`| ${ran.length > 0 && ran.every(status => status === "passed") ? "[x]" : "[ ]"} | \`${title.replace("param ", "")}\` | ${statuses.map(cell).join(" | ")} |`);
	});
	return { text: `${table.join("\n")}\n`, counts, total: titles.length };
};

const renderManual = () => {
	const manual = existsSync(manualPath) ? JSON.parse(readFileSync(manualPath, "utf8")) : { items: [] };
	const lines = [
		"## Manual checks",
		"",
		"These need real hardware or a real host application, so the suite cannot prove them. Record each result in `docs/parity/manual-results.json` and rerun the generator.",
		"",
		"| | Check | Result | Who, when |",
		"|---|---|---|---|"
	];
	manual.items.forEach(item => {
		lines.push(`| ${item.result === "pass" ? "[x]" : "[ ]"} | ${item.check} | ${item.result || "not done"} | ${item.by || ""} |`);
	});
	return lines.join("\n");
};

const main = () => {
	const { rows, startTime } = loadResults();
	const params = renderParams(rows);
	mkdirSync(join(repoRoot, "docs/parity"), { recursive: true });
	writeFileSync(join(repoRoot, "docs/parity/url-parameters.md"), params.text);

	const sections = [
		renderGroup(rows, "footprint.spec.ts", "1. Engine unchanged", "WebRTC, signaling, handshake, codec and URL-parameter behavior live in engine files that must stay byte-identical to upstream (`bn-shell/engine-lock.json`). Browser-independent; runs once."),
		renderGroup(rows, "dom-contract.spec.ts", "2. Views keep every engine element", "Each view loads in upstream and BytesNation side by side. Every element id upstream renders must exist with the same tag, the engine must reach the same state, and BytesNation must raise no page error upstream does not."),
		renderGroup(rows, "live-room.spec.ts", "3. Live room: director, two guests, scene, screen share, chat, mute, per-guest recording", "Real peers through the unmodified engine and its default signaling. Five sessions per run: director, two camera guests, a screen-share guest and a scene output."),
		renderGroup(rows, "shortcuts.spec.ts", "5. Keyboard shortcuts", "Same keys pressed in upstream and BytesNation on a live local publish; engine state must match afterwards."),
		renderGroup(rows, "iframe-api.spec.ts", "6. IFRAME API", "A host page sends the same messages to both; replies and events must match."),
		renderGroup(rows, "theme.spec.ts", "7. Theme, branding and output guarantees"),
		renderGroup(rows, "contrast.spec.ts", "8. WCAG AA contrast", "axe-core `color-contrast` across the main views in both themes. Text over live video is excluded because axe cannot read a video frame; those labels sit on an opaque scrim.")
	];

	const paramSection = [
		"## 4. URL parameters",
		"",
		`All ${params.total} parameters in the inventory. Full table: [parity/url-parameters.md](parity/url-parameters.md).`,
		"",
		`| Engine | Parameters run | Matched upstream |`,
		`|---|---|---|`,
		...projects.map(project => `| ${projectLabels[project]} | ${params.counts[project].ran} | ${params.counts[project].passed} |`)
	].join("\n");

	const allAutomated = rows.filter(row => row.status !== "skipped");
	const failures = allAutomated.filter(row => row.status === "failed");
	const header = [
		"# Parity checklist",
		"",
		"Built from [FEATURE-INVENTORY.md](FEATURE-INVENTORY.md). The redesign is done when every row is checked. Rows 1 to 8 are generated from the parity suite (`cd bn-shell && npm run test:parity && node scripts/render-parity-checklist.mjs`); the manual checks are recorded by hand.",
		"",
		`Last run: ${startTime || "unknown"}. ${allAutomated.length} automated checks ran across ${projects.length} engines; ${failures.length} failed.`,
		"",
		"Engines: Chrome, Firefox and Safari's WebKit run as desktop browsers; Android Chrome is a Pixel 7 profile and iOS Safari an iPhone 14 profile, both emulated. Where a headless engine has no fake camera (WebKit, and Firefox for more than one capture), the live room feeds a synthetic camera and microphone, and the notes say so. Real-device and real-picker runs are in the manual checks."
	].join("\n");

	const body = [header, sections[0].text, sections[1].text, sections[2].text, paramSection, sections[3].text, sections[4].text, sections[5].text, sections[6].text, renderManual()].join("\n\n");
	writeFileSync(join(repoRoot, "docs/PARITY-CHECKLIST.md"), `${body}\n`);
	process.stdout.write(`PARITY-CHECKLIST.md: ${allAutomated.length} automated checks, ${failures.length} failed\n`);
	failures.slice(0, 40).forEach(row => process.stdout.write(`  FAIL ${row.project} ${row.title}\n`));
};

main();
