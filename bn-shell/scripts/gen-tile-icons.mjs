const escapeAttribute = value => String(value).replace(/&/g, "&amp;").replace(/"/g, "&quot;");

/**
 * Serializes a Lucide icon node list to a standalone SVG string.
 * @param {Array<[string, Record<string, string>]>} iconNode
 * @returns {string}
 */
const renderSvg = iconNode => {
	const children = iconNode
		.map(([tagName, attributes]) => {
			const attributeText = Object.entries(attributes)
				.filter(([name]) => name !== "key")
				.map(([name, value]) => `${name}="${escapeAttribute(value)}"`)
				.join(" ");
			return `<${tagName} ${attributeText}/>`;
		})
		.join("");
	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${children}</svg>`;
};

const toDataUri = svg => `data:image/svg+xml,${encodeURIComponent(svg).replace(/'/g, "%27")}`;

const buildCss = async () => {
	const rules = [];
	for (const [tileId, iconName] of Object.entries(tileIcons)) {
		const { __iconData: iconData } = await import(join(iconDir, `${iconName}.mjs`));
		const uri = toDataUri(renderSvg(iconData.node));
		rules.push(`#${tileId}::after {\n\t-webkit-mask-image: url("${uri}");\n\tmask-image: url("${uri}");\n}`);
	}
	const header = "/* Generated by scripts/gen-tile-icons.mjs from Lucide (ISC). Do not edit by hand. */\n\n";
	writeFileSync(join(shellRoot, "src/theme/engine/tile-icons.css"), `${header}${rules.join("\n\n")}\n`);
	return rules.length;
};

const ruleCount = await buildCss();
process.stdout.write(`tile-icons.css: ${ruleCount} icons\n`);
