#!/usr/bin/env node
/**
 * Generates src/theme/engine/tile-icons.css: one masked Lucide icon (ISC) per
 * landing tile. Masks let the icon take the theme's text color in both themes;
 * upstream's tile icons are black-stroke background images that cannot.
 *
 * Usage: node scripts/gen-tile-icons.mjs
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const shellRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
